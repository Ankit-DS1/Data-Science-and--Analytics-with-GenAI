# Operators in python

# 1. Arithmetic operators

# +, -, *, /, %, **, //

a = 10
b = 3
print(a + b)  # 13
print(a - b)  # 7
print(a * b)  # 30
print(a / b)  # 3.333...
print(a % b)  # 1
print(a ** b) # 1000
print(a // b) # 3

#Assignment operators/shorthand operators
# =, +=, -=, *=, /=, %=, **=, //=

a = 10
a += 5  # a = a + 5
print(a)  # 15

# Concatenation operator
str1 = "Hello"
str2 = "World"
result = str1 + " " + str2
print(result)  # Hello World

#Multiplication operator
str3 = "Python"
result = str3 * 3
print(result)  # PythonPythonPython


                              # Comparison operators and Logical operators


# Comparison operators
# ==, !=, >, <, >=, <=

x = 5
y = 10
print(x == y)  # False
print(x != y)  # True
print(x > y)   # False
print(x < y)   # True
print(x >= y)  # False
print(x <= y)  # True

# Logical operators

# and, or, not

a = True
b = False
print(a and b)  # False , because both a and b need to be True for the result to be True
print(a or b)   # True , because at least one of a or b is True
print(not a)    # False , because a is True and not True is False



